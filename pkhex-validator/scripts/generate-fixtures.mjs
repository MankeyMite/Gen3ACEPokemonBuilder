function toHex(bytes) {
  return Array.from(bytes, byte => byte.toString(16).padStart(2, '0')).join('').toUpperCase();
}

function build(config) {
  const bytes = buildPokemonBytes(config).bytes;
  if (bytes.byteLength !== 80) throw new Error(`Builder returned ${bytes.byteLength} bytes.`);
  return bytes;
}

const legal = build(bulbasaur);
const illegal = build({ ...bulbasaur, moves: [354, 45, 0, 0] }); // Psycho Boost on Bulbasaur.
const badChecksum = legal.slice();
badChecksum[0x1C] ^= 0x01;
const eraDependent = build(eraDependentBulbasaur);

