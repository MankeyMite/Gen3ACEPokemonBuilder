const generated = `// Generated by scripts/generate-fixtures.mjs from the production Gen III builder.\nexport default ${JSON.stringify(fixtures, null, 2)};\n`;

if (process.argv.includes('--check')) {
  const existing = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : '';
  if (existing !== generated) {
    console.error('Generated fixtures are stale. Run: node pkhex-validator/scripts/generate-fixtures.mjs');
    process.exitCode = 1;
  }
} else {
  fs.writeFileSync(outputPath, generated, 'utf8');
  console.log(`Wrote ${outputPath}`);
}
