import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

import { SPECIES } from '../src/data/species.gen3.js';

const SOURCE_PAGES = Object.freeze({
  1: 'List_of_Japanese_Pokémon_names',
  3: 'List_of_French_Pokémon_names',
  5: 'List_of_German_Pokémon_names',
});

const LANGUAGE_CODES = Object.freeze({ 1: 'ja', 3: 'fr', 5: 'de' });
const OUTPUT_URL = new URL('../src/data/localizedSpeciesNames.gen3.js', import.meta.url);
const MAX_NATIONAL_DEX = 386;

function normalizeEnglishName(name) {
  return String(name || '')
    .normalize('NFKC')
    .replace(/♀/g, 'female')
    .replace(/♂/g, 'male')
    .toLowerCase()
    .replace(/[^a-z0-9]/g, '');
}

function formatGen3WesternName(name) {
  // Generations I-IV displayed French species names without diacritics or
  // ligatures. Keep that original-game formatting in the generated defaults.
  return String(name || '')
    .replace(/Œ/g, 'OE')
    .replace(/œ/g, 'oe')
    .normalize('NFD')
    .replace(/\p{M}/gu, '')
    .toUpperCase();
}

async function fetchWikitext(page) {
  const params = new URLSearchParams({
    action: 'parse',
    page,
    prop: 'wikitext',
    format: 'json',
  });
  const response = await fetch(`https://bulbapedia.bulbagarden.net/w/api.php?${params}`, {
    headers: { 'user-agent': 'Gen3ACEPokemonBuilder localization data updater' },
  });
  if (!response.ok) throw new Error(`Bulbapedia returned HTTP ${response.status} for ${page}`);
  const payload = await response.json();
  const wikitext = payload?.parse?.wikitext?.['*'];
  if (!wikitext) throw new Error(`Bulbapedia returned no wikitext for ${page}`);
  return wikitext;
}

function parseNames(wikitext, languageCode) {
  const namesByEnglish = new Map();
  const rowPattern = new RegExp(
    `\\{\\{Lop/foreign\\|(\\d{4})\\|([^|\\r\\n]+)\\|${languageCode}\\|([^|}\\r\\n]+)`,
    'g'
  );
  for (const match of wikitext.matchAll(rowPattern)) {
    const nationalDex = Number(match[1]);
    if (nationalDex < 1 || nationalDex > MAX_NATIONAL_DEX) continue;
    namesByEnglish.set(normalizeEnglishName(match[2]), match[3].trim());
  }
  if (namesByEnglish.size !== MAX_NATIONAL_DEX) {
    throw new Error(`Expected ${MAX_NATIONAL_DEX} ${languageCode} names, found ${namesByEnglish.size}`);
  }
  return namesByEnglish;
}

function serializeArray(name, values) {
  const rows = values.map(value => value == null ? 'null' : JSON.stringify(value));
  const lines = [];
  for (let index = 0; index < rows.length; index += 8) {
    lines.push(`  ${rows.slice(index, index + 8).join(', ')},`);
  }
  return `const ${name} = Object.freeze([\n${lines.join('\n')}\n]);`;
}

async function main() {
  const sourceEntries = await Promise.all(
    Object.entries(SOURCE_PAGES).map(async ([languageId, page]) => {
      const wikitext = await fetchWikitext(page);
      return [Number(languageId), parseNames(wikitext, LANGUAGE_CODES[languageId])];
    })
  );
  const sourceNames = new Map(sourceEntries);
  const maximumInternalId = Math.max(...SPECIES.map(([speciesId]) => speciesId));
  const english = new Array(maximumInternalId + 1).fill(null);
  const japanese = new Array(maximumInternalId + 1).fill(null);
  const french = new Array(maximumInternalId + 1).fill(null);
  const german = new Array(maximumInternalId + 1).fill(null);

  for (const [speciesId, englishName] of SPECIES) {
    if (speciesId < 1 || String(englishName).includes('?')) continue;
    const key = normalizeEnglishName(englishName);
    const japaneseName = sourceNames.get(1).get(key);
    const frenchName = sourceNames.get(3).get(key);
    const germanName = sourceNames.get(5).get(key);
    if (!japaneseName || !frenchName || !germanName) {
      throw new Error(`Missing localized data for internal species ${speciesId} (${englishName})`);
    }
    english[speciesId] = formatGen3WesternName(englishName);
    japanese[speciesId] = japaneseName;
    french[speciesId] = formatGen3WesternName(frenchName);
    german[speciesId] = formatGen3WesternName(germanName);
  }

  const generated = `// Generated by scripts/build-localized-species-names.js.\n` +
`// Refresh with: node scripts/build-localized-species-names.js\n` +
`// Sources: https://bulbapedia.bulbagarden.net/wiki/List_of_Japanese_Pokémon_names\n` +
`//          https://bulbapedia.bulbagarden.net/wiki/List_of_French_Pokémon_names\n` +
`//          https://bulbapedia.bulbagarden.net/wiki/List_of_German_Pokémon_names\n` +
`//          https://bulbapedia.bulbagarden.net/wiki/Localization\n` +
`// Spanish and Italian Gen 3 games use the English species names.\n` +
`// French names use their Generation III in-game, unaccented formatting.\n` +
`// Arrays are indexed by the Generation III internal species ID.\n\n` +
`${serializeArray('ENGLISH_SPECIES_NAMES', english)}\n\n` +
`${serializeArray('JAPANESE_SPECIES_NAMES', japanese)}\n\n` +
`${serializeArray('FRENCH_SPECIES_NAMES', french)}\n\n` +
`${serializeArray('GERMAN_SPECIES_NAMES', german)}\n\n` +
`export const SPECIES_NAMES_BY_LANGUAGE = Object.freeze({\n` +
`  1: JAPANESE_SPECIES_NAMES,\n` +
`  2: ENGLISH_SPECIES_NAMES,\n` +
`  3: FRENCH_SPECIES_NAMES,\n` +
`  4: ENGLISH_SPECIES_NAMES,\n` +
`  5: GERMAN_SPECIES_NAMES,\n` +
`  7: ENGLISH_SPECIES_NAMES,\n` +
`});\n\n` +
`export function getLocalizedSpeciesName(speciesId, languageId) {\n` +
`  const id = Number(speciesId);\n` +
`  const names = SPECIES_NAMES_BY_LANGUAGE[Number(languageId)] || ENGLISH_SPECIES_NAMES;\n` +
`  return names[id] || ENGLISH_SPECIES_NAMES[id] || '';\n` +
`}\n`;

  await writeFile(fileURLToPath(OUTPUT_URL), generated, 'utf8');
  console.log(`Wrote ${fileURLToPath(OUTPUT_URL)} with ${MAX_NATIONAL_DEX} localized species names.`);
}

await main();
