// Offline, reproducible import of the pinned Nintendo rejection/allowlist tries.
// Source data: abcboy101/badword (GPL-3.0); never use its optimized union here.
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';

const sourceUrl = new URL('../src/data/nintendoSwitchProfanity.v70.source.json', import.meta.url);
const outputUrl = new URL('../src/data/frlgProfanity.v70.js', import.meta.url);
const source = JSON.parse(await readFile(sourceUrl, 'utf8'));
assert.equal(source.version, 70);
const rules = new Map();
const exceptions = new Map();
function verify(file) {
  const bytes = Buffer.from(file.content, 'utf8');
  const hash = createHash('sha1').update(`blob ${bytes.length}\0`).update(bytes).digest('hex');
  assert.equal(hash, file.gitBlob, `Source hash mismatch: ${file.path}`);
}
for (const file of source.rejectionFiles) {
  verify(file);
  assert.ok(['b2', 'not_b'].includes(file.bucket), 'Masking-only data must not be imported');
  for (const raw of file.content.split('\n').filter(Boolean)) {
    const left = file.bucket === 'b2' && raw.startsWith('\\b');
    const right = file.bucket === 'b2' && raw.endsWith('\\b');
    assert.ok(file.bucket !== 'b2' || left || right, `Unrecognized boundary rule: ${raw}`);
    const term = raw.slice(left ? 2 : 0, right ? -2 : undefined);
    const mask = Number(left) | (Number(right) << 1);
    const key = JSON.stringify([term, mask]);
    if (!rules.has(key)) rules.set(key, [term, mask, []]);
    rules.get(key)[2].push(file.language);
  }
}
for (const file of source.allowlistFiles) {
  verify(file);
  assert.equal(file.applicableVersion, 70);
  assert.equal(file.equivalentTries.length, 2);
  for (const term of file.content.split('\n').filter(Boolean)) {
    if (!exceptions.has(term)) exceptions.set(term, []);
    exceptions.get(term).push(file.language);
  }
}
const compare = (a, b) => a < b ? -1 : a > b ? 1 : 0;
const lines = [...rules.values()].sort((a, b) => compare(JSON.stringify(a), JSON.stringify(b)));
const allow = [...exceptions].sort((a, b) => compare(a[0], b[0]));
const output = `// Generated by node scripts/build-frlg-profanity.mjs. Do not edit by hand.
// Nintendo data from https://github.com/${source.repository}/tree/${source.commit}
// GPL-3.0. Rejection rules only (b2 / not_b); no globally optimized union.
export const NINTENDO_FILTER_VERSION = 70;
export const NINTENDO_SOURCE_COMMIT = '${source.commit}';
export const NINTENDO_LANGUAGES = Object.freeze(${JSON.stringify(source.languages)});
const TYPES = ['substring', 'prefix', 'suffix', 'exact'];
const fileIndex = language => language === 'common' ? 'common' : NINTENDO_LANGUAGES.indexOf(language);
const escapeLiteral = term => term.replace(/[.*^$]/g, character => String.fromCharCode(92) + character);
export const NINTENDO_REJECTION_RULES = [
${lines.map(row => '  ' + JSON.stringify(row)).join(',\n')}
].map(([term, mask, languages]) => Object.freeze({
  id: 'v70:' + mask + ':' + term,
  term,
  pattern: (mask & 1 ? '^' : '.*') + escapeLiteral(term) + (mask & 2 ? '$' : '.*'),
  type: TYPES[mask],
  requiresLeftBoundary: Boolean(mask & 1),
  requiresRightBoundary: Boolean(mask & 2),
  sources: Object.freeze(languages.map(language => Object.freeze({
    language, version: 70,
    path: 'parsed/NgWord2/70/ac_' + fileIndex(language) + '_' + (mask ? 'b2' : 'not_b') + '_nx.txt',
    commit: NINTENDO_SOURCE_COMMIT,
  }))),
}));
// These v66 text parses have byte-identical forward/backward raw tries in v70.
// They are preserved for research; production does not assume FRLG applies them.
export const NINTENDO_ALLOWLIST = [
${allow.map(row => '  ' + JSON.stringify(row)).join(',\n')}
].map(([term, languages]) => Object.freeze({
  term,
  sources: Object.freeze(languages.map(language => Object.freeze({
    language, version: 70, parsedVersion: 66,
    path: 'parsed/NgWord2/66/trie_' + fileIndex(language) + '_allow.txt',
    equivalence: 'Both v70 raw allowlist tries have the same Git blob hashes as v66; see source snapshot.',
    commit: NINTENDO_SOURCE_COMMIT,
  }))),
}));
`;
if (process.argv.includes('--check')) {
  assert.equal(await readFile(outputUrl, 'utf8'), output, 'Generated profanity data is stale');
} else {
  await writeFile(outputUrl, output, 'utf8');
}
console.log(`Nintendo v70: ${lines.length} rejection rules, ${allow.length} allowlist literals; source hashes verified.`);
